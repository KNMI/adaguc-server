#ifndef DIMENSIONASLAYERS_H
#define DIMENSIONASLAYERS_H

#include <map>
#include <string>
#include <vector>
#include "CServerConfig_CPPXSD.h"
#include "CServerParams.h"

/**
 * A Dimension configured with aslayers="true" is not advertised as a dimension. Instead, the Layer is split into one layer per
 * distinct value of that dimension in the database. Each generated layer has the dimension fixed to its value and hidden.
 *
 * Example: model runs stored with a time dimension per run become one layer per run, each with only the elevation dimension.
 */

/** Distinct dimension values per FilePath, filter and dimension, to query them only once */
typedef std::map<std::string, std::vector<std::string>> DimensionValuesCache;

/** Returns true when the layer has a Dimension with aslayers="true". */
bool layerHasDimensionAsLayers(const CServerConfig::XMLE_Layer &layer);

/**
 * Makes one layer per distinct database value of the aslayers dimension of the given layer.
 * AdditionalLayers which have the same dimension follow the value of the generated layer: when the additional layer has the same aslayers
 * dimension, the generated layer refers to the layer it generates for that value; otherwise a hidden copy with the dimension fixed is made.
 * Returns an empty list when the layer has no aslayers dimension or when no values are found in the database.
 */
std::vector<CServerConfig::XMLE_Layer> makeLayersForDimensionValues(CServerParams *srvParam, const CServerConfig::XMLE_Layer &layer, DimensionValuesCache *cache = nullptr);

/**
 * Replaces every layer in srvParam->cfg->Layer that has an aslayers dimension with the layers generated by makeLayersForDimensionValues.
 * Must be called before CDataSources pointing to srvParam->cfg->Layer are created, because the layer list is reallocated.
 */
int expandDimensionsAsLayers(CServerParams *srvParam);

#endif
